"""Application-owned interfaces for external state and services.

Protocols are deliberately structural: production adapters and test fakes do
not inherit from them. Domain values cross these boundaries as plain dicts.
"""
from datetime import datetime
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class InvoiceStore(Protocol):
    def create_invoice(self, **fields) -> dict: ...
    def get_invoice(self, invoice_id: str) -> dict | None: ...
    def get_invoice_by_reply_token(self, reply_token: str) -> dict | None: ...
    def get_invoices_by_user(self, user_id: str) -> list[dict]: ...
    def update_invoice(self, invoice_id: str, *, only_if_unpaid: bool = False, **fields) -> dict | None: ...
    def mark_invoice_settled(self, invoice_id: str) -> bool: ...
    def upload_invoice_file(self, bucket: str, object_path: str, content: bytes, content_type: str) -> str: ...
    def download_invoice_file(self, bucket: str, path: str) -> bytes: ...


@runtime_checkable
class UserStore(Protocol):
    def upsert_user(self, **fields) -> dict: ...
    def get_user(self, user_id: str) -> dict | None: ...
    def get_user_by_email(self, email: str) -> dict | None: ...
    def get_user_gmail_tokens(self, user_id: str) -> tuple[str, str] | None: ...
    def update_user_gmail_tokens(self, user_id: str, access_token: str, refresh_token: str | None) -> None: ...
    def update_user_sender_profile(self, user_id: str, profile: dict) -> dict: ...
    def ensure_guest_user(self, guest_id: str) -> dict: ...
    def migrate_guest_to_user(self, guest_id: str, real_user_id: str) -> None: ...


@runtime_checkable
class CommunicationLog(Protocol):
    def add_communication(self, **fields) -> dict: ...
    def get_communications(self, invoice_id: str) -> list[dict]: ...
    def get_communications_for(self, invoice_ids: list[str]) -> dict[str, list[dict]]: ...
    def get_summary_communications(self, invoice_id: str) -> list[dict]: ...
    def get_last_outbound_delivery(self, invoice_id: str, kind: str) -> dict | None: ...
    def communication_flags(self, invoice_id: str) -> dict: ...
    def get_communication_overviews(self, invoice_ids: list[str]) -> dict[str, dict]: ...
    def get_invoice_summary(self, invoice_id: str) -> dict | None: ...
    def claim_invoice_summary(self, invoice_id: str, version: str, token: str) -> dict | None: ...
    def publish_invoice_summary(self, invoice_id: str, token: str, version: str, summary: str) -> bool: ...
    def progress_invoice_summary(self, invoice_id: str, token: str, version: str, progress: dict) -> bool: ...
    def release_invoice_summary(self, invoice_id: str, token: str, error: str | None = None) -> bool: ...


@runtime_checkable
class EmailSender(Protocol):
    def __call__(
        self,
        user_id: str,
        to_email: str,
        subject: str,
        body: str,
        thread_id: str | None = None,
        attachments: list[dict] | None = None,
        reply_to: list[str] | None = None,
    ) -> dict | None: ...


@runtime_checkable
class InboundMail(Protocol):
    def __call__(self, message_id: str) -> dict: ...


@runtime_checkable
class AgentSession(Protocol):
    def thread_config(self, invoice_id: str) -> dict: ...
    def get_state(self, invoice_id: str) -> Any: ...
    def update_state(self, invoice_id: str, values: dict) -> Any: ...
    def invoke(self, invoice_id: str, payload: Any, *, context: Any = None, config: dict | None = None) -> dict: ...
    def pending(self, invoice_id: str) -> Any: ...


@runtime_checkable
class TraceSink(Protocol):
    def insert_agent_run(self, row: dict) -> None: ...
    def insert_trace_steps(self, steps: list[dict]) -> None: ...
    def list_agent_runs(self, invoice_id: str, limit: int = 20, before: str | None = None) -> list[dict]: ...
    def get_trace_steps(self, run_ids: list[str]) -> dict[str, list[dict]]: ...


@runtime_checkable
class Clock(Protocol):
    def now(self) -> datetime: ...
